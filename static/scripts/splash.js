let splash = undefined;

while (splash == undefined && splashes.length > 0) {

    let index = Math.floor(Math.random() * splashes.length);
    let selection = splashes[index];

    if (typeof selection == typeof "string") {
        splash = selection;
        // I love Java because I don't have to do crap like this to check if a variable is of a certain interface
    } else if ("value" in selection) {

        let special = selection;

        // Skip disabled
        if (special.disabled) continue;

        // Check prerequisites
        let valid = true;
        if (special.prerequisites != undefined) {

            // 1-12 for Jan - Dec
            if (special.prerequisites.month != undefined) {
                if (new Date().getMonth() != special.prerequisites.month - 1) valid = false;
            }

            // Day of the month, 1-31
            if (special.prerequisites.day != undefined) {
                if (new Date().getDate() != special.prerequisites.day) valid = false;
            }

            // Hour of the day, 0-23
            if (special.prerequisites.hour != undefined) {
                if (new Date().getHours() != special.prerequisites.hour) valid = false;
            }

            // Minute of the hour, 0-59
            if (special.prerequisites.minute != undefined) {
                if (new Date().getMinutes() != special.prerequisites.minute) valid = false;
            }

            // Second of the hour, 0-59
            if (special.prerequisites.second != undefined) {
                if (new Date().getSeconds() != special.prerequisites.second) valid = false;
            }

            // Day of the week, 0-6 for Sun-Sat
            if (special.prerequisites.dotw != undefined) {
                if (new Date().getDay() != special.prerequisites.dotw) valid = false;
            }

        }

        if (valid) {
            splash = special.value;
        }

    }

    splashes.splice(index, 1);

}

var splashElement = document.getElementById("splash");
splashElement.innerHTML = (splash != undefined) ? splash : "undefined";
